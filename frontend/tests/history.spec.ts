import { test, expect } from '@playwright/test';

test('alertas: revisar, resolver, filtrar y persistir; historial: filtros y fechas inválidas', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('Correo electrónico').fill('e2e-admin@example.edu');
  await page.getByLabel('Contraseña', { exact: true }).fill('Only-E2E!92741');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await page.getByRole('link', { name: 'Alertas', exact: true }).click();
  let card = page.locator('article').filter({ hasText: 'Alerta sintética E2E' });
  await card.getByLabel('Estado de alerta').selectOption('review');
  await expect(card.getByLabel('Estado de alerta')).toHaveValue('review');
  await page.reload();
  await expect(card.getByLabel('Estado de alerta')).toHaveValue('review');
  await card.getByLabel('Estado de alerta').selectOption('resolved');
  await expect(card.getByLabel('Estado de alerta')).toHaveValue('resolved');
  await page.getByRole('button', { name: 'Resueltas', exact: true }).click();
  await expect(card).toBeVisible();
  await card.getByText(/Historial de cambios/).click();
  await expect(card.getByRole('list')).toBeVisible();
  await page.screenshot({ path: '../tmp/alerts-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Historial', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Historial de análisis' })).toBeVisible();
  await page.getByLabel('Desde', { exact: true }).fill('2026-12-31');
  await page.getByLabel('Hasta', { exact: true }).fill('2026-01-01');
  await page.getByRole('button', { name: 'Buscar', exact: true }).click();
  await expect(page.getByText('La fecha inicial debe ser anterior o igual a la final.')).toBeVisible();
  await page.getByRole('button', { name: 'Limpiar filtros' }).click();
  await expect(page.getByRole('heading', { name: 'Resultados', exact: true })).toBeVisible();
  await page.getByLabel('Estado', { exact: true }).selectOption('completed');
  await page.getByRole('button', { name: 'Buscar', exact: true }).click();
  await expect(page).toHaveURL(/status=completed/);
  await page.reload();
  await expect(page.getByLabel('Estado', { exact: true })).toHaveValue('completed');
  const reportDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Descargar reporte consolidado PDF' }).click();
  const report = await reportDownload;
  expect(report.suggestedFilename()).toBe('reporte-ocupacion.pdf');
  expect(await report.failure()).toBeNull();
  await page.getByRole('link', { name: 'Reportes', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Reportes de capacidad y ocupación' })).toBeVisible();
  await page.screenshot({ path: '../tmp/history-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '../tmp/history-mobile.png', fullPage: true });
});
